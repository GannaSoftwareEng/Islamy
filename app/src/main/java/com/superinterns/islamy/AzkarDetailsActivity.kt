package com.superinterns.islamy

import android.content.Intent
import android.os.Bundle
import android.widget.Button
import android.widget.TextView
import androidx.appcompat.app.AppCompatActivity
import androidx.core.content.ContextCompat
import androidx.core.view.ViewCompat
import androidx.core.view.WindowInsetsCompat
import androidx.core.view.WindowInsetsControllerCompat

data class Zikr(
    val text: String,
    val source: String,
    val count: Int
)

class AzkarDetailsActivity : AppCompatActivity() {

    private lateinit var btnCount: Button
    private lateinit var tvZikr: TextView
    private lateinit var tvSource: TextView
    private lateinit var tvTitle: TextView

    private var currentZikr = 0
    private var remainingCount = 0

    private var azkarList = listOf<Zikr>()

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        setContentView(R.layout.activity_azkar_details)

        btnCount = findViewById(R.id.btnCount)
        tvZikr = findViewById(R.id.tvZikr)
        tvSource = findViewById(R.id.tvSource)
        tvTitle = findViewById(R.id.tvTitle)

        val btnNext = findViewById<Button>(R.id.btnNext)
        val btnPrevious = findViewById<Button>(R.id.btnPrevious)
        val btnBack = findViewById<TextView>(R.id.btnBack)

        // Category coming from AzkarActivity
        val category = intent.getStringExtra("category") ?: "morning"

        // Load the correct Azkar list
        azkarList = getAzkarByCategory(category)

        // Change page title
        tvTitle.text = getCategoryTitle(category)

        btnBack.setOnClickListener {

            finish()
        }


        window.statusBarColor =
            ContextCompat.getColor(this, R.color.greenlight)

        WindowInsetsControllerCompat(window, window.decorView)
            .isAppearanceLightStatusBars = false

        // First Zikr
        loadZikr()

        // Count button
        btnCount.setOnClickListener {

            if (remainingCount > 1) {

                remainingCount--
                btnCount.text = remainingCount.toString()

            } else {

                goToNextZikr()
            }
        }

        // Next
        btnNext.setOnClickListener {
            goToNextZikr()
        }

        // Previous
        btnPrevious.setOnClickListener {
            goToPreviousZikr()
        }
    }

    // =========================================================
    // Load current Zikr
    // =========================================================

    private fun loadZikr() {

        if (azkarList.isEmpty()) return

        val zikr = azkarList[currentZikr]

        tvZikr.text = zikr.text
        tvSource.text = zikr.source

        remainingCount = zikr.count

        btnCount.text = remainingCount.toString()
    }

    // =========================================================
    // Next Zikr
    // =========================================================

    private fun goToNextZikr() {

        if (currentZikr < azkarList.size - 1) {

            currentZikr++

            loadZikr()
        }
    }

    // =========================================================
    // Previous Zikr
    // =========================================================

    private fun goToPreviousZikr() {

        if (currentZikr > 0) {

            currentZikr--

            loadZikr()
        }
    }

    // =========================================================
    // Category Title
    // =========================================================

    private fun getCategoryTitle(category: String): String {

        return when (category) {

            "morning" -> "Morning Azkar"

            "evening" -> "Evening Azkar"

            "daily" -> "Daily Azkar"

            "after_prayer" -> "After Prayer"

            "before_sleep" -> "Before Sleep"

            "tasbeeh" -> "Tasbeeh"

            "duaa" -> "Duaa"

            else -> "Azkar"
        }
    }

    // =========================================================
    // Get Azkar according to category
    // =========================================================

    private fun getAzkarByCategory(category: String): List<Zikr> {

        return when (category) {

            "morning" -> morningAzkar()

            "evening" -> eveningAzkar()

            "tasbeeh" -> tasbeehAzkar()

            "after_prayer" -> afterPrayerAzkar()

            "before_sleep" -> beforeSleepAzkar()

            "daily" -> dailyAzkar()

            "duaa" -> duaaAzkar()

            else -> morningAzkar()
        }
    }

